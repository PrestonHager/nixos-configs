# ace-secret-rotate: rotate the secrets that ace both generates and consumes.
# Sourced by nixos/security/secret-rotation.nix (which exports the ACE_* paths).
# See docs/secret-rotation.md for what is and is not covered.
#
# Usage: ace-secret-rotate [--dry-run] [--no-mail] all | NAME...
#
# Every rotator keeps the previous value next to the new one and puts it back if
# the post-rotation check fails, so a failed run leaves the service as it was.
# Secrets never go on a command line: this host has no hidepid and auditd logs
# every EXECVE, so values only move through files and shell builtins.
set -uo pipefail

STATE="${ACE_ROTATE_STATE:?}"
PROM="${ACE_ROTATE_PROM:?}"
ALL=(valkey-pterodactyl valkey-nextcloud valkey-mediawiki technitium-admin technitium-pfx update-signing-key wg-portal-web)

DRY=0
MAIL=1
names=()
for a in "$@"; do
  case "$a" in
    --dry-run) DRY=1 ;;
    --no-mail) MAIL=0 ;;
    all) names+=("${ALL[@]}") ;;
    -h|--help) sed -n '2,12p' "$0" 2>/dev/null; printf 'Secrets: %s\n' "${ALL[*]}"; exit 0 ;;
    *) names+=("$a") ;;
  esac
done
[[ ${#names[@]} -gt 0 ]] || { echo "usage: ace-secret-rotate [--dry-run] [--no-mail] all | ${ALL[*]}" >&2; exit 2; }

umask 077
mkdir -p "$STATE/status"
REPORT="$(mktemp)"
trap 'rm -f "$REPORT"' EXIT

log() { printf '%s %s\n' "$(date -Is)" "$*" | tee -a "$REPORT" >&2; }

# 64 hex characters (256 bits): no characters that need quoting or URL encoding.
new_secret() { od -An -tx1 -N32 /dev/urandom | tr -d ' \n'; }

# Wait up to $1 seconds for "$2..." to succeed.
wait_for() {
  local t="$1"; shift
  local end=$((SECONDS + t))
  until "$@" >/dev/null 2>&1; do
    (( SECONDS >= end )) && return 1
    sleep 3
  done
}

http_ok() { curl -s -o /dev/null -m 10 -w '%{http_code}' "$1" | grep -qE '^(200|301|302|303)$'; }

# phpredis AUTH + PING from inside an app container, reading the password from
# the container's own environment variable $2.
php_redis_ok() {
  podman exec "$1" php -r '$r = new Redis(); $r->connect("127.0.0.1", 6379, 5);
    exit(($r->auth(getenv($argv[1])) && $r->ping()) ? 0 : 1);' "$2"
}

restart() { systemctl restart "$@"; }

# --- Valkey / Redis passwords generated by the *-redis-auth units -----------
# $1 app  $2 password dir  $3 redis container  $4 env var in app container
# $5 app containers (space separated)  $6 health URL
rotate_valkey() {
  local app="$1" dir="$2" redis="$3" var="$4" apps="$5" url="$6" c
  [[ -s "$dir/password" ]] || { log "$app: $dir/password missing"; return 1; }
  if (( DRY )); then log "$app: would rotate $dir/password and restart ${redis} ${apps}"; return 0; fi

  cp -a "$dir/password" "$dir/password.prev"
  new_secret > "$dir/password.tmp" && mv -f "$dir/password.tmp" "$dir/password"

  if apply_valkey "$app" "$redis" "$apps" && check_valkey "$app" "$redis" "$var" "$apps" "$url"; then
    rm -f "$dir/password.prev"
    log "$app: rotated"
    return 0
  fi
  log "$app: check failed, restoring the previous password"
  mv -f "$dir/password.prev" "$dir/password"
  apply_valkey "$app" "$redis" "$apps" || true
  if check_valkey "$app" "$redis" "$var" "$apps" "$url"; then
    log "$app: previous password restored, service healthy"
  else
    log "$app: STILL UNHEALTHY after restoring the previous password"
  fi
  return 1
}

apply_valkey() {
  local app="$1" redis="$2" apps="$3" c
  restart "${app}-redis-auth.service" || return 1
  restart "podman-${redis}.service" || return 1
  for c in $apps; do restart "podman-${c}.service" || return 1; done
}

check_valkey() {
  local app="$1" redis="$2" var="$3" apps="$4" url="$5" c first="${4%% *}"
  wait_for 60 podman exec --env-file "/var/lib/redis-auth/${app}/app.env" "$redis" \
    sh -c 'exec "$(command -v valkey-cli || command -v redis-cli)" ping' || { log "$app: $redis does not accept the new password"; return 1; }
  # MediaWiki installs phpredis at container start; give it time.
  wait_for 300 podman exec "$first" php -m || return 1
  wait_for 300 sh -c "podman exec $first php -m | grep -qx redis" || { log "$app: phpredis not loaded in $first"; return 1; }
  wait_for 120 php_redis_ok "$first" "$var" || { log "$app: $first cannot AUTH to $redis"; return 1; }
  for c in $apps; do
    wait_for 60 sh -c "[ \"\$(podman inspect -f '{{.State.Running}}' $c)\" = true ]" || { log "$app: container $c not running"; return 1; }
  done
  wait_for 300 http_ok "$url" || { log "$app: $url not healthy"; return 1; }
}

# --- Technitium admin password (used by the technitium-* sync units) --------
TECH_API=http://127.0.0.1:5380
TECH_PASS=/stor/technitium/secrets/admin-password

tech_login() {  # $1 password file -> token on stdout
  curl -sf -X POST "$TECH_API/api/user/login" --data-urlencode "user=admin" --data-urlencode "pass@$1" \
    | jq -er 'select(.status == "ok") | .token'
}

rotate_technitium_admin() {
  local tmp token
  [[ -s "$TECH_PASS" ]] || { log "technitium-admin: $TECH_PASS missing"; return 1; }
  if (( DRY )); then log "technitium-admin: would change the admin password via /api/user/changePassword"; return 0; fi
  tmp="$(mktemp -d)"
  token="$(tech_login "$TECH_PASS")" || { log "technitium-admin: cannot log in with the current password"; rm -rf "$tmp"; return 1; }
  new_secret > "$tmp/new"
  printf 'Authorization: Bearer %s\n' "$token" > "$tmp/auth"
  if ! curl -sf -X POST "$TECH_API/api/user/changePassword" -H "@$tmp/auth" \
      --data-urlencode "pass@$TECH_PASS" --data-urlencode "newPass@$tmp/new" | jq -e '.status == "ok"' >/dev/null; then
    log "technitium-admin: changePassword failed; password unchanged"
    rm -rf "$tmp"; return 1
  fi
  cp -a "$TECH_PASS" "$TECH_PASS.prev"
  install -m 0600 "$tmp/new" "$TECH_PASS.tmp" && mv -f "$TECH_PASS.tmp" "$TECH_PASS"
  rm -rf "$tmp"
  if tech_login "$TECH_PASS" >/dev/null && systemctl restart technitium-sync-zones.service; then
    rm -f "$TECH_PASS.prev"
    log "technitium-admin: rotated"
    return 0
  fi
  log "technitium-admin: new password does not log in; the old one is kept in $TECH_PASS.prev for manual recovery"
  return 1
}

# --- Technitium PFX export password (DoT certificate bundle) ----------------
TECH_PFX_PASS=/stor/technitium/secrets/pfx-password

rotate_technitium_pfx() {
  [[ -s "$TECH_PFX_PASS" ]] || { log "technitium-pfx: $TECH_PFX_PASS missing"; return 1; }
  if (( DRY )); then log "technitium-pfx: would regenerate $TECH_PFX_PASS and re-export the certificate"; return 0; fi
  cp -a "$TECH_PFX_PASS" "$TECH_PFX_PASS.prev"
  new_secret > "$TECH_PFX_PASS.tmp" && mv -f "$TECH_PFX_PASS.tmp" "$TECH_PFX_PASS"
  if systemctl restart technitium-sync-tls-cert.service && systemctl restart technitium-sync-protocols.service \
      && wait_for 60 sh -c 'echo | openssl s_client -connect 192.168.5.5:853 -servername dns.prestonhager.com 2>/dev/null | grep -q "subject=CN=dns.prestonhager.com"'; then
    rm -f "$TECH_PFX_PASS.prev"
    log "technitium-pfx: rotated"
    return 0
  fi
  log "technitium-pfx: re-export failed, restoring the previous password"
  mv -f "$TECH_PFX_PASS.prev" "$TECH_PFX_PASS"
  systemctl restart technitium-sync-tls-cert.service technitium-sync-protocols.service || true
  return 1
}

# --- HMAC key for the update approval links ---------------------------------
UPDATE_STATE=/var/lib/ace-service-update

rotate_update_signing_key() {
  local key="$UPDATE_STATE/signing-key"
  if [[ -n "$(ls -A "$UPDATE_STATE/pending" 2>/dev/null)" ]]; then
    log "update-signing-key: skipped, an upgrade approval mail is pending (its links would stop working)"
    return 0
  fi
  if (( DRY )); then log "update-signing-key: would regenerate $key"; return 0; fi
  new_secret > "$key.tmp" && chmod 0600 "$key.tmp" && mv -f "$key.tmp" "$key"
  systemctl try-restart ace-service-update-http.service
  log "update-signing-key: rotated"
}

# --- wg-portal web session and CSRF secrets (generated, see wg-portal.nix) --
WGP_SECRETS=/var/lib/wg-portal-secrets

rotate_wg_portal_web() {
  local f
  if (( DRY )); then log "wg-portal-web: would regenerate the session/CSRF secrets and restart wg-portal (signs everyone out)"; return 0; fi
  for f in session csrf; do
    [[ -s "$WGP_SECRETS/$f" ]] && cp -a "$WGP_SECRETS/$f" "$WGP_SECRETS/$f.prev"
    new_secret > "$WGP_SECRETS/$f.tmp" && mv -f "$WGP_SECRETS/$f.tmp" "$WGP_SECRETS/$f"
  done
  if restart podman-wg-portal.service && wait_for 90 http_ok http://127.0.0.1:8888/; then
    rm -f "$WGP_SECRETS"/*.prev
    log "wg-portal-web: rotated"
    return 0
  fi
  log "wg-portal-web: wg-portal unhealthy, restoring the previous secrets"
  for f in session csrf; do [[ -f "$WGP_SECRETS/$f.prev" ]] && mv -f "$WGP_SECRETS/$f.prev" "$WGP_SECRETS/$f"; done
  restart podman-wg-portal.service || true
  return 1
}

run_one() {
  case "$1" in
    valkey-pterodactyl) rotate_valkey pterodactyl /var/lib/redis-auth/pterodactyl pterodactyl-redis REDIS_PASSWORD \
                          "pterodactyl" "https://panel.prestonhager.com/auth/login" ;;
    valkey-nextcloud)   rotate_valkey nextcloud /var/lib/redis-auth/nextcloud nextcloud-redis REDIS_HOST_PASSWORD \
                          "nextcloud nextcloud-notify-push" "https://cloud.prestonhager.com/status.php" ;;
    valkey-mediawiki)   rotate_valkey mediawiki /var/lib/redis-auth/mediawiki mediawiki-redis MW_REDIS_PASSWORD \
                          "mediawiki" "https://loftiawiki.org/" ;;
    technitium-admin)   rotate_technitium_admin ;;
    technitium-pfx)     rotate_technitium_pfx ;;
    update-signing-key) rotate_update_signing_key ;;
    wg-portal-web)      rotate_wg_portal_web ;;
    *) log "unknown secret: $1"; return 2 ;;
  esac
}

write_metrics() {
  local tmp="$PROM.$$" f n
  {
    echo "# HELP ace_secret_rotation_success 1 when the last rotation of this secret succeeded."
    echo "# TYPE ace_secret_rotation_success gauge"
    echo "# HELP ace_secret_rotation_last_success_timestamp_seconds When this secret was last rotated successfully."
    echo "# TYPE ace_secret_rotation_last_success_timestamp_seconds gauge"
    for f in "$STATE"/status/*.ok "$STATE"/status/*.fail; do
      [[ -e "$f" ]] || continue
      n="$(basename "$f")"; n="${n%.*}"
      case "$f" in
        *.ok)   echo "ace_secret_rotation_last_success_timestamp_seconds{secret=\"$n\"} $(stat -c %Y "$f")" ;;
      esac
    done
    for n in "${ALL[@]}"; do
      if [[ -e "$STATE/status/$n.fail" && ! "$STATE/status/$n.fail" -ot "$STATE/status/$n.ok" ]]; then
        echo "ace_secret_rotation_success{secret=\"$n\"} 0"
      elif [[ -e "$STATE/status/$n.ok" ]]; then
        echo "ace_secret_rotation_success{secret=\"$n\"} 1"
      fi
    done
  } > "$tmp"
  chown node_exporter:node_exporter "$tmp" 2>/dev/null || true
  chmod 0644 "$tmp"
  mv -f "$tmp" "$PROM"
}

exec 9>/run/ace-service-update-rebuild.lock
flock -w 1800 9 || { log "rebuild lock busy for 30 minutes; not rotating"; exit 1; }

failed=()
for n in "${names[@]}"; do
  log "== $n"
  if run_one "$n"; then
    (( DRY )) || touch "$STATE/status/$n.ok"
  else
    failed+=("$n")
    (( DRY )) || touch "$STATE/status/$n.fail"
  fi
done
(( DRY )) || write_metrics

if (( MAIL && ! DRY )) && [[ -n "${ACE_UPDATE_MAIL:-}" ]]; then
  if [[ ${#failed[@]} -gt 0 ]]; then
    subject="Ace secret rotation FAILED: ${failed[*]}"
  else
    subject="Ace secret rotation ok: ${names[*]}"
  fi
  "$ACE_UPDATE_MAIL" --subject "$subject" --body-file "$REPORT" || log "could not send the report mail"
fi

[[ ${#failed[@]} -eq 0 ]]
